import { mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import type {
  SharedMcpServer,
  SharedResourceRequest,
  SharedResourcesProvider,
} from "@codexhost/harness-adapter/plugin";

/** Pi registers MCP servers from an extension and loads skills from folders natively. */
export const PI_SHARED_RESOURCE_REQUEST: SharedResourceRequest = Object.freeze({
  harnessId: "pi",
  mcp: true,
  skills: true,
  skillFiles: true,
  memory: true,
  memoryMcp: true,
});

export interface PiSharedLaunch {
  /** `--extension`: registers the shared MCP servers with `pi.registerMcpServer`. */
  readonly extension?: string;
  /** `--skill`, one per folder. */
  readonly skills: readonly string[];
  /** `--append-system-prompt <file>`: the memory instruction (no credentials). */
  readonly systemPromptFile?: string;
  dispose(): Promise<void>;
}

/**
 * Pi's MCP config shape (`McpServerConfig` of pi-coding-agent ≥ 1.3): stdio `command/args/env`,
 * http `url/headers`.
 */
export function renderPiMcp(servers: Record<string, SharedMcpServer>): Record<string, unknown> {
  return Object.fromEntries(
    Object.entries(servers).map(([name, server]) => [
      name,
      server.type === "stdio"
        ? { type: "stdio", command: server.command, args: server.args, env: server.env }
        : { type: "http", url: server.url, headers: server.headers },
    ]),
  );
}

/**
 * Per-process files in a private temporary folder, removed when the Pi process ends: the
 * extension carries MCP options (which may hold credentials) and never reaches the model; older Pi
 * versions without MCP skip the registration instead of failing.
 */
export async function preparePiSharedResources(
  provider: SharedResourcesProvider | undefined,
  cwd: string,
): Promise<PiSharedLaunch> {
  const none: PiSharedLaunch = { skills: [], dispose: async () => {} };
  if (!provider) return none;
  const shared = await provider(cwd, PI_SHARED_RESOURCE_REQUEST).catch(() => undefined);
  if (!shared) return none;
  const servers = renderPiMcp(shared.mcpServers);
  const skills = (shared.skills ?? []).map((skill) => skill.directory);
  if (!Object.keys(servers).length && !shared.context && !skills.length) return none;
  const directory = await mkdtemp(path.join(os.tmpdir(), "rly0-pi-shared-"));
  try {
    let extension: string | undefined;
    if (Object.keys(servers).length) {
      extension = path.join(directory, "rly0-shared-mcp.js");
      await writeFile(
        extension,
        [
          "// Generated by RLY/0 Hub for one Pi process; removed when it ends.",
          `const servers = ${JSON.stringify(servers)};`,
          "export default function rly0SharedMcp(pi) {",
          '  if (typeof pi.registerMcpServer !== "function") return;',
          "  for (const [name, config] of Object.entries(servers)) pi.registerMcpServer(name, config);",
          "}",
          "",
        ].join("\n"),
        { mode: 0o600 },
      );
    }
    let systemPromptFile: string | undefined;
    if (shared.context) {
      systemPromptFile = path.join(directory, "rly0-shared-context.md");
      await writeFile(systemPromptFile, `${shared.context}\n`, { mode: 0o600 });
    }
    return {
      ...(extension ? { extension } : {}),
      skills,
      ...(systemPromptFile ? { systemPromptFile } : {}),
      dispose: () => rm(directory, { recursive: true, force: true }),
    };
  } catch (error) {
    await rm(directory, { recursive: true, force: true });
    throw error;
  }
}

/** Command-line arguments for the prepared files. */
export function piSharedArguments(launch: PiSharedLaunch | undefined): string[] {
  if (!launch) return [];
  return [
    ...(launch.extension ? ["--extension", launch.extension] : []),
    ...launch.skills.flatMap((directory) => ["--skill", directory]),
    ...(launch.systemPromptFile ? ["--append-system-prompt", launch.systemPromptFile] : []),
  ];
}
